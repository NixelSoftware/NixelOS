#!/usr/bin/env python3
"""Generate shared OS identity; build ID is HEAD's committer Unix timestamp."""
from pathlib import Path
import re
import subprocess
import sys

root = Path(__file__).resolve().parent.parent
version = (root / 'VERSION').read_text().strip()
if not re.fullmatch(r'[0-9]+\.[0-9]+\.[0-9]+(?:-[A-Za-z0-9.-]+)?', version):
    sys.exit('VERSION must contain a semantic version such as 0.1.0')
try:
    build_id = subprocess.check_output(
        ['git', '-C', str(root), 'log', '-1', '--format=%ct'],
        stderr=subprocess.DEVNULL, text=True).strip()
except (OSError, subprocess.CalledProcessError):
    build_id = '0'  # Source archives without Git metadata have an unknown build ID.
if not build_id.isdecimal():
    sys.exit('Invalid Git committer timestamp')
content = f'''/* Generated by tools/generate_version.py; do not edit. */
#ifndef NIXELOS_VERSION_H
#define NIXELOS_VERSION_H
#define OS_NAME "NixelOS"
#define OS_VERSION "{version}"
#define OS_BUILD_ID "{build_id}"
#define OS_VERSION_DESCRIPTION OS_NAME " " OS_VERSION " (build " OS_BUILD_ID ")"
#endif
'''
output = root / 'src/include/os_version.h'
if not output.exists() or output.read_text() != content:
    output.write_text(content)
