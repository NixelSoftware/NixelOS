#!/usr/bin/env python3
from pathlib import Path
import sys

assets = Path(__file__).resolve().parent / 'assets'
lines = ['/* Generated by embed_assets.py; do not edit. */',
         '#ifndef CHESS_PIECE_ASSETS_H', '#define CHESS_PIECE_ASSETS_H']
names = []
for side in ('l', 'd'):
    for piece in 'pnbrqk':
        name = f'piece_{side}_{piece}'
        data = (assets / f'Chess_{piece}{side}t60.png').read_bytes()
        lines.append(f'static const uint8_t {name}[] = {{')
        lines.extend('    ' + ','.join(f'0x{b:02x}' for b in data[i:i+16]) + ','
                     for i in range(0, len(data), 16))
        lines.append('};')
        names.append(name)
lines.append('static const struct { const uint8_t *data; uint32_t size; } piece_assets[12] = {')
lines.extend(f'    {{ {name}, sizeof({name}) }},' for name in names)
lines.extend(['};', '#endif', ''])
Path(sys.argv[1]).write_text('\n'.join(lines))
